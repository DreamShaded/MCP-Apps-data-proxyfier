import type { Page } from "playwright";

/**
 * Шов браузера: даёт инструментам эксклюзивный доступ к единственной странице,
 * сериализованный мьютексом. Инструменты (`check_session`, позже
 * `search_products` и т.д.) зависят от этого интерфейса, а не от Playwright
 * напрямую — в тестах подставляется фейковый драйвер.
 */
export interface BrowserDriver {
  /**
   * Выполнить `fn`, получив эксклюзивный доступ к единственной странице.
   * Параллельные вызовы выстраиваются в очередь (один контекст / одна вкладка).
   */
  withPage<T>(fn: (page: Page) => Promise<T>): Promise<T>;
  /** Закрыть браузер и освободить профиль. Повторный вызов безопасен. */
  close(): Promise<void>;
}
