/**
 * Минимальный асинхронный мьютекс: сериализует доступ к единственной странице
 * браузера. Единственная сессия Сбера / единственный контекст — параллельные
 * действия дрались бы за одну вкладку и злили антибот, поэтому все обращения
 * проходят строго по очереди.
 */
export class Mutex {
  /** Хвост очереди: каждый новый запуск ждёт завершения предыдущего. */
  private tail: Promise<void> = Promise.resolve();

  /**
   * Выполнить `fn` эксклюзивно. Запуски сериализуются в порядке вызова; ошибка
   * одного запуска не рвёт очередь — следующий стартует в любом случае.
   */
  runExclusive<T>(fn: () => Promise<T>): Promise<T> {
    const run = this.tail.then(fn, fn);
    // Хвост проглатывает результат/ошибку, чтобы не пробрасывать их следующему в очереди.
    this.tail = run.then(
      () => undefined,
      () => undefined,
    );
    return run;
  }
}
